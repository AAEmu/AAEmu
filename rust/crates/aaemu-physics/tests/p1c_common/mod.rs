//! Shared by the P1c integration tests: running a P1c probe (a C file built on
//! `tests/p1c_common.h`), golden handling, and parsing the probe's `mesh` dump (every field of a
//! DLL `CTriMesh`, `p1c_mesh_dump`) back into a [`TriMesh`].
//!
//! | env | effect |
//! |---|---|
//! | `AAEMU_PHYS_P1C_PROBE_DIR=<dir>` | directory holding the built probes (`<name>.exe`); goldens are regenerated and must match |
//! | + `AAEMU_PHYS_BLESS=1` | mismatching / missing goldens are rewritten |
//! | none | the goldens under `tests/golden/p1c_*.trace` are used |
#![allow(dead_code)]

use aaemu_physics::geometry::bvtree::select::MeshTree;
use aaemu_physics::geometry::bvtree::{AabbTree, MemReader, ObbTree, SingleBoxTree};
use aaemu_physics::geometry::trimesh::{MeshIsland, TriMesh};
use aaemu_physics::math::Vec3;
use std::path::{Path, PathBuf};
use std::process::Command;

/// `<crate>/tests/golden`.
pub fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("golden")
}

/// The probe `<name>.exe` from `AAEMU_PHYS_P1C_PROBE_DIR`, if configured and present.
pub fn probe(name: &str) -> Option<PathBuf> {
    let d = PathBuf::from(std::env::var_os("AAEMU_PHYS_P1C_PROBE_DIR")?);
    let p = d.join(format!("{name}.exe"));
    p.is_file().then_some(p)
}

fn bless() -> bool {
    std::env::var_os("AAEMU_PHYS_BLESS").is_some_and(|v| v != "0")
}

/// Runs a probe with arguments; its stdout.
pub fn run_probe(exe: &Path, args: &[&str]) -> Result<String, String> {
    let out = Command::new(exe)
        .args(args)
        .output()
        .map_err(|e| format!("cannot run {}: {e}", exe.display()))?;
    let text = String::from_utf8(out.stdout).map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(format!(
            "probe {} failed ({}): {}",
            exe.display(),
            out.status,
            text.lines().last().unwrap_or("")
        ));
    }
    Ok(text.replace("\r\n", "\n"))
}

/// The golden `tests/golden/<name>.trace`: regenerated by `probe_name args` when the probe is
/// available (must match the stored file unless blessing), else read from disk. `None` when
/// neither exists.
pub fn golden(name: &str, probe_name: &str, args: &[&str]) -> Option<String> {
    let path = golden_dir().join(format!("{name}.trace"));
    let stored = std::fs::read_to_string(&path)
        .ok()
        .map(|s| s.replace("\r\n", "\n"));
    let fresh =
        probe(probe_name).map(|exe| run_probe(&exe, args).unwrap_or_else(|e| panic!("{e}")));
    match (fresh, stored) {
        (None, s) => s,
        (Some(f), Some(s)) if f == s => Some(s),
        (Some(f), stored) => {
            if bless() || stored.is_none() {
                std::fs::write(&path, &f)
                    .unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
                return Some(f);
            }
            let s = stored.unwrap_or_default();
            let first = f
                .lines()
                .zip(s.lines())
                .enumerate()
                .find(|(_, (a, b))| a != b)
                .map(|(i, (a, b))| format!("line {}:\n  probe:  {a}\n  golden: {b}", i + 1))
                .unwrap_or_else(|| "length differs".into());
            panic!(
                "{} differs from the DLL ({first}); set AAEMU_PHYS_BLESS=1 to rewrite",
                path.display()
            );
        }
    }
}

/// Text diff helper: panics with the first differing line.
pub fn assert_same_text(what: &str, port: &str, dll: &str) {
    if port == dll {
        return;
    }
    let (pl, dl): (Vec<_>, Vec<_>) = (port.lines().collect(), dll.lines().collect());
    for i in 0..pl.len().max(dl.len()) {
        let a = pl.get(i).copied().unwrap_or("<eof>");
        let b = dl.get(i).copied().unwrap_or("<eof>");
        if a != b {
            panic!("{what}: line {}\n  port: {a}\n  dll:  {b}", i + 1);
        }
    }
}

fn hexw(s: &str) -> u32 {
    u32::from_str_radix(s, 16).unwrap_or_else(|_| panic!("bad hex word {s}"))
}

fn ints(rest: &[&str]) -> Vec<i32> {
    rest.iter().map(|s| s.parse().unwrap()).collect()
}

fn words(rest: &[&str]) -> Vec<u32> {
    rest.iter().map(|s| hexw(s)).collect()
}

fn vecs(w: &[u32]) -> Vec<Vec3> {
    w.chunks(3)
        .map(|c| {
            Vec3::new(
                f32::from_bits(c[0]),
                f32::from_bits(c[1]),
                f32::from_bits(c[2]),
            )
        })
        .collect()
}

/// Parses one `p1c_mesh_dump` block (the lines from `mesh …` through `tree …`) into a
/// [`TriMesh`] with every field the dump carries. Returns the mesh and the number of lines used.
pub fn parse_mesh_dump(lines: &[&str]) -> (TriMesh, usize) {
    let mut m = TriMesh::default();
    let mut used = 0;
    for (i, line) in lines.iter().enumerate() {
        let t: Vec<&str> = line.split_whitespace().collect();
        if t.is_empty() {
            continue;
        }
        let rest = &t[1..];
        match t[0] {
            "mesh" => {
                let get = |k: &str| -> &str {
                    let p = t.iter().position(|x| *x == k).unwrap();
                    t[p + 1]
                };
                m.n_tris = get("nt").parse().unwrap();
                m.n_verts = get("nv").parse().unwrap();
                m.flags = hexw(get("flags"));
                m.max_vertex_valency = get("valency").parse().unwrap();
                m.min_vtx_dist = f32::from_bits(hexw(get("mvd")));
                m.priority = get("prio").parse().unwrap();
                m.is_convex = get("convex").parse().unwrap();
                m.multi_island = get("multi").parse().unwrap();
                m.ray_grid_ready = get("raygrid").parse().unwrap();
                m.i_vtx_min = get("vmin").parse().unwrap();
            }
            "idx" => m.indices = ints(rest),
            "vtx" => m.vertices = vecs(&words(rest)),
            "nrm" => m.normals = vecs(&words(rest)),
            "topo" => {
                m.topology = ints(rest).chunks(3).map(|c| [c[0], c[1], c[2]]).collect();
            }
            "mats" => {
                m.mats = (rest.first() != Some(&"-"))
                    .then(|| ints(rest).into_iter().map(|v| v as i8).collect());
            }
            "fid" => m.foreign_idx = (rest.first() != Some(&"-")).then(|| ints(rest)),
            "vmap" => m.vtx_map = (rest.first() != Some(&"-")).then(|| ints(rest)),
            "aux" => m.aux = (rest.first() != Some(&"-")).then(|| ints(rest)),
            "islands" => {
                m.islands = (rest.first() != Some(&"-")).then(|| {
                    words(&rest[1..])
                        .chunks(10)
                        .map(|c| {
                            let mut w = [0u32; 10];
                            w.copy_from_slice(c);
                            MeshIsland { words: w }
                        })
                        .collect()
                });
            }
            "tisl" => m.tri_island = (rest.first() != Some(&"-")).then(|| words(rest)),
            "cache" => {
                let w = words(rest);
                for k in 0..4 {
                    m.convex_cache[k] = w[k] as i32;
                    m.convex_tol[k] = f32::from_bits(w[4 + k]);
                }
                // w[8] is +512 (multi_island, already from the header line)
                m.cached_volume = f32::from_bits(w[9]);
                m.cached_extent = [f32::from_bits(w[10]), f32::from_bits(w[11])];
                m.cached_center = Vec3::new(
                    f32::from_bits(w[12]),
                    f32::from_bits(w[13]),
                    f32::from_bits(w[14]),
                );
            }
            "misc" => {
                let v = ints(rest);
                m.n_bad_edges = v[0];
                m.n_errors = v[1];
            }
            "tree" => {
                used = i + 1;
                if rest.first() == Some(&"-") {
                    m.tree = None;
                } else {
                    let ty: i32 = rest[0].parse().unwrap();
                    let hex = rest[3];
                    let bytes: Vec<u8> = (0..hex.len() / 2)
                        .map(|k| u8::from_str_radix(&hex[2 * k..2 * k + 2], 16).unwrap())
                        .collect();
                    let mut r = MemReader::new(&bytes);
                    m.tree = Some(match ty {
                        0 => MeshTree::Obb(ObbTree::load(&mut r, m.n_tris).unwrap()),
                        1 => MeshTree::Aabb(AabbTree::load(&mut r, m.n_tris).unwrap()),
                        2 => MeshTree::SingleBox(SingleBoxTree::load(&mut r).unwrap()),
                        t => panic!("tree type {t}"),
                    });
                    // the constructor marks the tree convex (BV slot `SetGeomConvex`) for a
                    // convex mesh; the stream does not carry it for every tree type
                    if m.is_convex != 0 {
                        use aaemu_physics::geometry::bvtree::BvTree;
                        match m.tree.as_mut() {
                            Some(MeshTree::Obb(t)) => t.set_geom_convex(),
                            Some(MeshTree::Aabb(t)) => t.set_geom_convex(),
                            Some(MeshTree::SingleBox(t)) => t.set_geom_convex(),
                            None => {}
                        }
                    }
                }
                break;
            }
            _ => {}
        }
    }
    (m, used)
}

/// A mesh file in the probes' input format: `u32 nVerts, u32 nTris, f32 verts[3·nVerts],
/// i32 idx[3·nTris]` (little endian), written to a temp file; returns its path.
pub fn write_mesh_file(tag: &str, v: &[Vec3], idx: &[i32]) -> PathBuf {
    let mut b = Vec::new();
    b.extend((v.len() as u32).to_le_bytes());
    b.extend(((idx.len() / 3) as u32).to_le_bytes());
    for p in v {
        for c in [p.x, p.y, p.z] {
            b.extend(c.to_bits().to_le_bytes());
        }
    }
    for i in idx {
        b.extend(i.to_le_bytes());
    }
    let dir = std::env::temp_dir().join(format!("aaemu-p1c-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let p = dir.join(format!("{tag}.mesh"));
    std::fs::write(&p, b).unwrap();
    p
}

fn hex_bytes(b: &[u8]) -> String {
    use std::fmt::Write;
    let mut s = String::with_capacity(2 * b.len());
    for x in b {
        let _ = write!(s, "{x:02x}");
    }
    s
}

/// The port's [`TriMesh`] in the text format of `p1c_mesh_dump` (p1c_common.h), for direct
/// comparison with a probe's dump.
pub fn dump_mesh(m: &TriMesh) -> String {
    use aaemu_physics::geometry::bvtree::MemWriter;
    use std::fmt::Write;
    let nt = m.n_tris.max(0) as usize;
    let nv = m.n_verts.max(0) as usize;
    let mut s = String::new();
    let _ = writeln!(
        s,
        "mesh nt {} nv {} flags {:08x} valency {} mvd {:08x} prio {} convex {} multi {} raygrid {} vmin {}",
        m.n_tris,
        m.n_verts,
        m.flags,
        m.max_vertex_valency,
        m.min_vtx_dist.to_bits(),
        m.priority,
        m.is_convex,
        m.multi_island,
        m.ray_grid_ready,
        m.i_vtx_min
    );
    s += "idx";
    for i in &m.indices[..3 * nt] {
        let _ = write!(s, " {i}");
    }
    s += "\nvtx";
    for v in &m.vertices[..nv] {
        let _ = write!(
            s,
            " {:08x} {:08x} {:08x}",
            v.x.to_bits(),
            v.y.to_bits(),
            v.z.to_bits()
        );
    }
    s += "\nnrm";
    for v in &m.normals[..nt] {
        let _ = write!(
            s,
            " {:08x} {:08x} {:08x}",
            v.x.to_bits(),
            v.y.to_bits(),
            v.z.to_bits()
        );
    }
    s += "\ntopo";
    for t in &m.topology[..nt] {
        let _ = write!(s, " {} {} {}", t[0], t[1], t[2]);
    }
    s += "\n";
    let list = |s: &mut String, tag: &str, v: Option<Vec<String>>| {
        match v {
            Some(v) => {
                *s += tag;
                for x in v {
                    *s += " ";
                    *s += &x;
                }
            }
            None => {
                *s += tag;
                *s += " -";
            }
        }
        *s += "\n";
    };
    list(
        &mut s,
        "mats",
        m.mats
            .as_ref()
            .map(|a| a[..nt].iter().map(|x| x.to_string()).collect()),
    );
    list(
        &mut s,
        "fid",
        m.foreign_idx
            .as_ref()
            .map(|a| a[..nt].iter().map(|x| x.to_string()).collect()),
    );
    list(
        &mut s,
        "vmap",
        m.vtx_map
            .as_ref()
            .map(|a| a[..nv].iter().map(|x| x.to_string()).collect()),
    );
    list(
        &mut s,
        "aux",
        m.aux
            .as_ref()
            .map(|a| a[..nt].iter().map(|x| x.to_string()).collect()),
    );
    match &m.islands {
        Some(isl) => {
            let _ = write!(s, "islands {}", isl.len());
            for i in isl {
                for w in i.words {
                    let _ = write!(s, " {w:08x}");
                }
            }
            s += "\n";
        }
        None => s += "islands -\n",
    }
    list(
        &mut s,
        "tisl",
        m.tri_island
            .as_ref()
            .map(|a| a[..nt].iter().map(|x| format!("{x:08x}")).collect()),
    );
    s += "cache";
    let mut w: Vec<u32> = m.convex_cache.iter().map(|&x| x as u32).collect();
    w.extend(m.convex_tol.iter().map(|x| x.to_bits()));
    w.push(m.multi_island as u32);
    w.push(m.cached_volume.to_bits());
    w.extend(m.cached_extent.iter().map(|x| x.to_bits()));
    w.extend(
        [m.cached_center.x, m.cached_center.y, m.cached_center.z]
            .iter()
            .map(|x| x.to_bits()),
    );
    for x in w {
        let _ = write!(s, " {x:08x}");
    }
    let _ = writeln!(s, "\nmisc {} {}", m.n_bad_edges, m.n_errors);
    match &m.tree {
        Some(t) => {
            let mut wr = MemWriter::new();
            t.as_dyn().save(&mut wr);
            let b = wr.into_bytes();
            let _ = writeln!(
                s,
                "tree {} bytes {} {}",
                t.as_dyn().tree_type().id(),
                b.len(),
                hex_bytes(&b)
            );
        }
        None => s += "tree -\n",
    }
    s
}

/// Masks the bytes of a serialized tree (slot 21 payload of type `ty`, as hex) that the DLL's
/// builders leave uninitialised: AABB node 1 (all but nTris) and the `single_coll` byte of
/// internal AABB nodes; OBB node 1 (all but iParent and nTris).
pub fn mask_tree_hex(ty: i32, hex: &str) -> String {
    let mut b: Vec<char> = hex.chars().collect();
    let mut blank = |from: usize, n: usize| {
        for c in b.iter_mut().skip(2 * from).take(2 * n) {
            *c = '-';
        }
    };
    let byte = |i: usize| u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).unwrap_or(0);
    let word = |i: usize| u32::from_le_bytes([byte(i), byte(i + 1), byte(i + 2), byte(i + 3)]);
    match ty {
        1 if hex.len() >= 16 && word(0) == u32::MAX => {
            let n = word(4) as usize;
            for k in 0..n {
                let o = 8 + 12 * k;
                if 2 * (o + 12) > hex.len() {
                    break;
                }
                if k == 1 {
                    blank(o, 10);
                    blank(o + 11, 1);
                } else if byte(o + 10) == 0 {
                    blank(o + 11, 1);
                }
            }
        }
        0 if hex.len() >= 8 => {
            let n = word(0) as usize;
            if n >= 2 && hex.len() >= 2 * (4 + 144) {
                let o = 4 + 72;
                blank(o, 60);
                blank(o + 64, 4);
            }
        }
        _ => {}
    }
    b.into_iter().collect()
}

/// [`mask_tree_hex`] applied to the `tree` lines of a dump text.
pub fn mask_dump(text: &str) -> String {
    let mut out = String::new();
    for line in text.lines() {
        let f: Vec<&str> = line.split(' ').collect();
        if f.len() == 5 && f[0] == "tree" && f[2] == "bytes" {
            let ty: i32 = f[1].parse().unwrap_or(-1);
            out += &format!("tree {} bytes {} {}", f[1], f[3], mask_tree_hex(ty, f[4]));
        } else {
            out += line;
        }
        out += "\n";
    }
    out
}

/// Hex text → bytes.
pub fn unhex(h: &str) -> Vec<u8> {
    (0..h.len() / 2)
        .map(|k| u8::from_str_radix(&h[2 * k..2 * k + 2], 16).unwrap())
        .collect()
}

/// Bytes → hex text.
pub fn hex(b: &[u8]) -> String {
    hex_bytes(b)
}
