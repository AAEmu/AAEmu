//! The Rust parameter layouts and their "unused" defaults, sent byte for byte to the real DLL:
//! a SetParams / Action built from `Default::default()` must leave the entity unchanged, and the
//! same structs with a few fields set must have the documented effect.
//!
//! The scenario is generated from the Rust structs; it is checked in as
//! `tests/scenarios/params_neutral.scn` (so CI notices layout drift) and its oracle output as
//! `tests/golden/params_neutral.trace`.

use aaemu_physics::math::{Quat, Vec3};
use aaemu_physics::oracle::{scenario_dir, scenario_trace};
use aaemu_physics::params::*;

/// Byte offsets of the CRigidEntity object a default call may change: a (zero) impulse always
/// wakes the body — simclass byte (+68..+71: sleeping 1 → active 2), +132 bitfield and the
/// awake byte +508 — but must not touch the momenta.
fn allowed_changes(name: &str) -> &'static [usize] {
    match name {
        "action_impulse" => &[68, 132, 508],
        _ => &[],
    }
}

fn neutral_calls() -> Vec<(&'static str, String)> {
    let p = |t: i32, hex: String| format!("params target=box type={t} tmpl=none hex={hex}");
    let a = |t: i32, hex: String| format!("action target=box type={t} tmpl=none hex={hex}");
    vec![
        (
            "params_pos",
            p(ParamsPos::TYPE_ID, ParamsPos::default().to_hex()),
        ),
        (
            "params_part",
            p(ParamsPart::TYPE_ID, ParamsPart::default().to_hex()),
        ),
        (
            "params_simulation",
            p(
                ParamsSimulation::TYPE_ID,
                ParamsSimulation::default().to_hex(),
            ),
        ),
        (
            "params_buoyancy",
            p(ParamsBuoyancy::TYPE_ID, ParamsBuoyancy::default().to_hex()),
        ),
        (
            "params_flags",
            p(ParamsFlags::TYPE_ID, ParamsFlags::default().to_hex()),
        ),
        (
            "params_foreign_data",
            p(
                ParamsForeignData::TYPE_ID,
                ParamsForeignData::default().to_hex(),
            ),
        ),
        (
            "params_timeout",
            p(ParamsTimeout::TYPE_ID, ParamsTimeout::default().to_hex()),
        ),
        (
            "action_impulse",
            a(ActionImpulse::TYPE_ID, ActionImpulse::default().to_hex()),
        ),
        (
            "action_set_velocity",
            a(
                ActionSetVelocity::TYPE_ID,
                ActionSetVelocity::default().to_hex(),
            ),
        ),
    ]
}

/// The scenario text generated from the Rust defaults.
fn scenario() -> String {
    let mut s = String::from(
        "# GENERATED by tests/params_oracle.rs from the Rust parameter structs - do not edit.\n\
         # Neutral-default check: every SetParams/Action below is a Rust Default::default() image;\n\
         # snapdiff lists the byte offsets of the rigid entity's 0x4B0-byte object each call changed.\n\
         grid axisz=2 org=0,0,-100 n=64,64 step=4,4\n\
         geom name=ground type=box size=50,50,0.5\n\
         geom name=cube type=box size=0.5,0.5,0.5\n\
         entity name=ground type=static pos=32,32,-0.5\n\
         part ent=ground geom=ground mass=0\n\
         entity name=box type=rigid pos=32,32,0.48\n\
         part ent=box geom=cube mass=10\n\
         trace ents=box\n\
         step n=40 every=0\n",
    );
    for (name, call) in neutral_calls() {
        s += &format!("echo {name}\nsnap target=box n=300\n{call}\nsnapdiff target=box\n");
    }
    // Non-default values through the same layouts.
    let pos = ParamsPos {
        pos: Vec3::new(30.0, 31.0, 5.0),
        q: Quat::new(0.0, 0.0, 0.258_819, 0.965_925_8),
        ..Default::default()
    };
    s += &format!(
        "echo set_pos\nparams target=box type=0 tmpl=none hex={}\nprint\n",
        pos.to_hex()
    );
    let vel = ActionSetVelocity {
        v: Vec3::new(1.0, 2.0, 3.0),
        w: Vec3::new(0.0, 0.0, 1.0),
        ..Default::default()
    };
    s += &format!(
        "echo set_velocity\naction target=box type=10 tmpl=none hex={}\nprint\n",
        vel.to_hex()
    );
    let imp = ActionImpulse {
        impulse: Vec3::new(0.0, 0.0, 50.0),
        ..Default::default()
    };
    s += &format!(
        "echo impulse\naction target=box type=2 tmpl=none hex={}\nprint\n",
        imp.to_hex()
    );
    let sim = ParamsSimulation {
        gravity: Vec3::new(0.0, 0.0, -2.0),
        ..Default::default()
    };
    s += &format!(
        "echo sim_gravity\nparams target=box type=10 tmpl=none hex={}\n",
        sim.to_hex()
    );
    s += "peek target=box off=616 n=6\ntrace ents=box\nstep n=1\n";
    s
}

#[test]
fn scenario_file_is_current() {
    let path = scenario_dir().join("params_neutral.scn");
    let want = scenario();
    let have = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    if have != want {
        if std::env::var_os("AAEMU_PHYS_BLESS").is_some() {
            std::fs::write(&path, &want).unwrap();
        } else {
            panic!(
                "{} is out of date with the Rust layouts; rerun with AAEMU_PHYS_BLESS=1",
                path.display()
            );
        }
    }
}

#[test]
fn default_structs_are_neutral_in_the_dll() {
    let t = scenario_trace("params_neutral").unwrap_or_else(|e| panic!("{e}"));
    let diffs: Vec<&Vec<String>> = t.other.iter().filter(|l| l[0] == "snapdiff").collect();
    let calls = neutral_calls();
    assert_eq!(diffs.len(), calls.len());
    for ((name, _), d) in calls.iter().zip(diffs) {
        let changed: Vec<usize> = d[2..].iter().map(|o| o.parse().unwrap()).collect();
        let unexpected: Vec<usize> = changed
            .iter()
            .copied()
            .filter(|o| !allowed_changes(name).contains(o))
            .collect();
        assert!(
            unexpected.is_empty(),
            "{name}: default struct changed entity bytes at offsets {unexpected:?}"
        );
    }
    // every call was accepted
    for r in t
        .rets
        .iter()
        .filter(|r| r[0] == "params" || r[0] == "action")
    {
        assert_ne!(r[3], "0", "call rejected: {r:?}");
    }
}

#[test]
fn set_values_take_effect_in_the_dll() {
    let t = scenario_trace("params_neutral").unwrap_or_else(|e| panic!("{e}"));
    // print after set_pos, set_velocity, impulse; then one traced step
    let prints: Vec<_> = t.steps.iter().collect();
    let after_pos = &prints[prints.len() - 4].entities[0];
    assert_eq!(after_pos.pos_f(), Vec3::new(30.0, 31.0, 5.0));
    assert_eq!(after_pos.q_f().z, 0.258_819);
    let after_vel = &prints[prints.len() - 3].entities[0];
    assert_eq!(after_vel.v_f().unwrap(), Vec3::new(1.0, 2.0, 3.0));
    let after_imp = &prints[prints.len() - 2].entities[0];
    assert_eq!(after_imp.v_f().unwrap().z, 3.0 + 50.0 / 10.0);
    // simulation params: gravity (+616) and gravityFreefall (+628) both set to (0,0,-2)
    let g = t
        .other
        .iter()
        .rev()
        .find(|l| l[0] == "peek" && l[2] == "616")
        .unwrap();
    let words: Vec<u32> = g[3..]
        .iter()
        .map(|w| u32::from_str_radix(w, 16).unwrap())
        .collect();
    assert_eq!(
        words,
        vec![0, 0, (-2.0f32).to_bits(), 0, 0, (-2.0f32).to_bits()]
    );
}
